// Отложенная отметка «прочитано» (02 SCR-44.4 «Отметки о прочтении — единый механизм»; ядро §19.4; 07 §11.2).
// Отметка сразу применяется к кэшу `notifications_cache.read_at` и ставится в `outbox_actions` типа
// `notification.read` (payload — `id` или флаг `readAll`); запись переживает перезапуск и уходит при
// восстановлении сети (идемпотентно). Используется, когда онлайн-запрос не дошёл до сервера. Чистый Dart (FL-01).

abstract interface class NotificationReadQueue {
  /// Отметить [notificationId] прочитанным локально и поставить в очередь. `false` — БД пользователя не открыта
  /// (отметка не сохранена: экран держит её только в памяти).
  Future<bool> enqueueRead(String notificationId);

  /// «Прочитать все» локально + запись очереди `{readAll: true, before}`; [before] по умолчанию — момент вызова
  /// (действие пользователя), чтобы пришедшие позже уведомления не отмечались (08 §4.16.2). `false` — БД не открыта.
  Future<bool> enqueueReadAll({DateTime? before});
}
